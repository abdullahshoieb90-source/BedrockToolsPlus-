// The vanilla scripts block for 1.26.60.5. It is what makes variable.tcos0,
// variable.attack_body_rot_y and the layer flags exist, so the pack has to
// carry it for our Molang to have anything to read.
inline nlohmann::json vanillaScripts() {
    return nlohmann::json{
        {"scale", "0.9375"},
        {"initialize",
         {"variable.is_holding_right = 0.0;", "variable.is_blinking = 0.0;", "variable.last_blink_time = 0.0;",
          "variable.hand_bob = 0.0;"}},
        {"pre_animation",
         {"variable.helmet_layer_visible = !query.has_head_gear;", "variable.leg_layer_visible = 1.0;",
          "variable.boot_layer_visible = 1.0;", "variable.chest_layer_visible = 1.0;",
          "variable.attack_body_rot_y = Math.sin(360*Math.sqrt(variable.attack_time)) * 5.0;",
          "variable.tcos0 = (math.cos(query.modified_distance_moved * 38.17) * query.modified_move_speed / "
          "variable.gliding_speed_value) * 57.3;",
          "variable.first_person_rotation_factor = math.sin((1 - variable.attack_time) * 180.0);",
          "variable.hand_bob = query.life_time < 0.01 ? 0.0 : variable.hand_bob + ((query.is_on_ground && "
          "query.is_alive ? math.clamp(math.sqrt(math.pow(query.position_delta(0), 2.0) + "
          "math.pow(query.position_delta(2), 2.0)), 0.0, 0.1) : 0.0) - variable.hand_bob) * 0.02;",
          "variable.map_angle = math.clamp(1 - variable.player_x_rotation / 45.1, 0.0, 1.0);",
          "variable.item_use_normalized = query.main_hand_item_use_duration / "
          "query.main_hand_item_max_duration;",
          "variable.riding_y_offset = query.is_riding_any_entity_of_type('minecraft:minecart', "
          "'minecraft:boat', 'minecraft:chest_boat', 'minecraft:strider') ? -3.0 : 0.0;"}},
        {"animate", {"root"}},
        {"variables",
         {{"variable.fp_melee_spear_use_attachable_rotation_z", "public"},
          {"variable.tp_melee_spear_use_attachable_rotation_z", "public"},
          {"variable.fp_melee_spear_attack_attachable_rotation_z", "public"},
          {"variable.tp_melee_spear_attack_attachable_position_z", "public"},
          {"variable.attack_time", "public"},
          {"variable.item_use_normalized", "public"}}},
        {"should_update_effects_offscreen", "1.0"}};
}

inline nlohmann::json buildEntity(const ModelSettings& settings) {
    nlohmann::json bindings = nlohmann::json::object();
    for (const auto& entry : vanillaBindings()) bindings[entry.first] = entry.second;

    if (settings.moveArms) bindings["move.arms"] = kAnimMoveArms;
    if (settings.attack) bindings["attack.rotations"] = kAnimAttack;
    if (settings.bob) bindings["bob"] = kAnimBob;
    if (settings.sneak) bindings["sneaking"] = kAnimSneak;
    if (settings.useItem) bindings["use_item_progress"] = kAnimUseItem;
    if (settings.holding) bindings["holding"] = kAnimHolding;

    nlohmann::json description = nlohmann::json::object();
    description["identifier"] = "minecraft:player";
    description["materials"] = {{"default", "entity_alphatest"},
                                {"cape", "entity_alphatest"},
                                {"animated", "player_animated"},
                                {"spectator", "player_spectator"}};
    description["textures"] = {{"default", "textures/entity/steve"}, {"cape", "textures/entity/cape_invisible"}};
    description["geometry"] = {{"default", "geometry.humanoid.custom"}, {"cape", "geometry.cape"}};
    description["scripts"] = vanillaScripts();
    description["animations"] = std::move(bindings);
    description["render_controllers"] = {
        {{"controller.render.player.first_person_spectator", "variable.is_first_person && query.is_spectator"}},
        {{"controller.render.player.third_person_spectator",
          "!variable.is_first_person && !variable.map_face_icon && query.is_spectator"}},
        {{"controller.render.player.first_person", "variable.is_first_person && !query.is_spectator"}},
        {{"controller.render.player.third_person",
          "!variable.is_first_person && !variable.map_face_icon && !query.is_spectator"}},
        {{"controller.render.player.map", "variable.map_face_icon"}}};
    description["enable_attachables"] = true;

    return nlohmann::json{{"format_version", "1.26.0"},
                          {"minecraft:client_entity", nlohmann::json{{"description", std::move(description)}}}};
}

inline nlohmann::json buildManifest() {
    nlohmann::json header;
    header["name"] = kPackName;
    header["description"] = kPackDescription;
    header["uuid"] = kHeaderUuid;
    header["version"] = {1, 0, 0};
    header["min_engine_version"] = {1, 26, 0};

    nlohmann::json module;
    module["description"] = kPackDescription;
    module["type"] = "resources";
    module["uuid"] = kModuleUuid;
    module["version"] = {1, 0, 0};

    return nlohmann::json{{"format_version", 2}, {"header", std::move(header)}, {"modules", nlohmann::json::array({module})}};
}

inline std::vector<File> buildPack(const ModelSettings& settings) {
    return {
        {"manifest.json", buildManifest().dump(2) + "\n"},
        {"animations/java17_player.animation.json", buildAnimations(settings).dump(2) + "\n"},
        {"entity/player.entity.json", buildEntity(settings).dump(2) + "\n"},
    };
}

// Every animation id the entity file can point at, so a generated pack can be
// checked for dangling references before it is written.
inline std::vector<std::string> animationIds(const ModelSettings& settings) {
    std::vector<std::string> ids;
    if (settings.moveArms) ids.emplace_back(kAnimMoveArms);
    if (settings.attack) ids.emplace_back(kAnimAttack);
    if (settings.bob) ids.emplace_back(kAnimBob);
    if (settings.sneak) ids.emplace_back(kAnimSneak);
    if (settings.useItem) ids.emplace_back(kAnimUseItem);
    if (settings.holding) ids.emplace_back(kAnimHolding);
    return ids;
}

