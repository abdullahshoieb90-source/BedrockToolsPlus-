// A no-op animation in the vanilla idiom (see animation.humanoid.base_pose):
// used when an override has to exist but must not move anything.
inline nlohmann::json noopAnimation() {
    return nlohmann::json{{"loop", true},
                          {"bones", nlohmann::json{{"waist", nlohmann::json{{"rotation", nlohmann::json::array({0.0, 0.0, 0.0})}}}}}};
}

// Java 1.7 walk/run: the arms swing the full width, the hands stay down.
inline nlohmann::json moveArmsAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"leftarm", nlohmann::json{{"rotation", {"variable.tcos0 * 1.15", 0.0, 0.0}}}},
             {"rightarm", nlohmann::json{{"rotation", {"-variable.tcos0 * 1.15", 0.0, 0.0}}}},
         }}};
}

// Java 1.7 attack: one overhead chop. The shape is the vanilla one (it is
// driven by variable.attack_time, which the engine owns), scaled to the
// constants of the Java 1.7 arm: a 1.2 rad lift (68.75 degrees) with the
// 0.4 rad roll (-22.9 degrees), and the arm follows where you are looking.
// Vanilla Bedrock lifts 30 degrees; 1.7 lifts almost 70.
inline nlohmann::json attackAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"body", nlohmann::json{{"rotation", {0.0, "variable.attack_body_rot_y", 0.0}}}},
             {"leftarm", nlohmann::json{{"rotation", {0.0, "variable.attack_body_rot_y * 2.0", 0.0}}}},
             {"rightarm",
              nlohmann::json{
                  {"rotation",
                   {"-(math.sin((1 - math.pow((1 - variable.attack_time), 4)) * 180.0) * 68.75 + "
                    "math.sin(variable.attack_time * 180.0) * (query.head_x_rotation(0) - 20.0) * 0.35)",
                    "variable.attack_body_rot_y * 2.0",
                    "math.sin(variable.attack_time * 180.0) * -22.9"}}}},
         }}};
}

// Java 1.7 idle: the arms hang straight (Bedrock cants them outwards by ~2.9
// degrees) and the chest breathes instead.
inline nlohmann::json bobAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"body", nlohmann::json{{"rotation", {"math.sin(query.life_time * 76.78) * 0.6", 0.0, 0.0}}}},
         }}};
}

// Java 1.7 crouch: the body drops, the arms hang almost straight instead of
// being pushed forward.
inline nlohmann::json sneakingAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"body", nlohmann::json{{"position", {0.0, -2.2, 0.8}}}},
             {"head", nlohmann::json{{"position", {0.0, -1.0, 0.0}}}},
             {"leftarm", nlohmann::json{{"rotation", {-2.0, 0.0, 0.0}}}},
             {"rightarm", nlohmann::json{{"rotation", {-2.0, 0.0, 0.0}}}},
             {"leftleg", nlohmann::json{{"rotation", {-28.0, -0.1, -0.1}}}},
             {"rightleg", nlohmann::json{{"rotation", {-28.0, 0.1, 0.1}}}},
             {"root", nlohmann::json{{"position", {0.0, 1.25, 9.0}}, {"rotation", {"28.0 - this", 0.0, 0.0}}}},
         }}};
}

// Java 1.7 eat/drink: the whole arm comes up to the mouth (vanilla lifts 60
// degrees, 1.7 lifts ~95) and the head tips back a little. The nibble rides on
// the engine's own interval progress so it stays in step with the bites.
inline nlohmann::json useItemAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"rightarm",
              nlohmann::json{
                  {"rotation",
                   {"variable.use_item_startup_progress * -95.0 + variable.use_item_interval_progress * 8.0",
                    "variable.use_item_startup_progress * -18.0",
                    "variable.use_item_startup_progress * -6.0"}}}},
             {"head", nlohmann::json{{"rotation", {"variable.use_item_startup_progress * -10.0", 0.0, 0.0}}}},
         }}};
}

// Java 1.7 holds items with a straight arm; Bedrock bends the arm up by 18
// degrees. Vanilla's version is `-this * 0.5 - 18.0`, so removing the bend is
// just dropping the constant - the arm keeps half of its walk swing, which is
// what the vanilla expression is for.
inline nlohmann::json holdingAnimation() {
    return nlohmann::json{
        {"loop", true},
        {"bones",
         nlohmann::json{
             {"leftarm", nlohmann::json{{"rotation", {"variable.is_holding_left ? (-this * 0.5) : 0.0", 0.0, 0.0}}}},
             {"rightarm", nlohmann::json{{"rotation", {"variable.is_holding_right ? (-this * 0.5) : 0.0", 0.0, 0.0}}}},
         }}};
}

inline nlohmann::json buildAnimations(const ModelSettings& settings) {
    nlohmann::json animations = nlohmann::json::object();
    if (settings.moveArms) animations[kAnimMoveArms] = moveArmsAnimation();
    if (settings.attack) animations[kAnimAttack] = attackAnimation();
    if (settings.bob) animations[kAnimBob] = bobAnimation();
    if (settings.sneak) animations[kAnimSneak] = sneakingAnimation();
    if (settings.useItem) animations[kAnimUseItem] = useItemAnimation();
    if (settings.holding) animations[kAnimHolding] = holdingAnimation();
    return nlohmann::json{{"format_version", "1.10.0"}, {"animations", animations}};
}

